export function renderPictureTapIcon(vectorIconKey: string, size = 32) {
  switch (vectorIconKey) {
    case 'compass':
      return <CompassIcon size={size} />;
    case 'map':
      return <MapIcon size={size} />;
    case 'tree':
      return <TreeIcon size={size} />;
    case 'tent':
      return <TentIcon size={size} />;
    case 'lantern':
      return <LanternIcon size={size} />;
    case 'boots':
      return <BootsIcon size={size} />;
    case 'backpack':
      return <BackpackIcon size={size} />;
    case 'campfire':
    case 'fire':
      return <CampfireIcon size={size} />;
    default:
      return <CompassIcon size={size} />;
  }
}
